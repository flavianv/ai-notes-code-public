# Builds narration.json from script.md and data.js from facts.json (results.json), and checks every spoken figure against the cited facts.
import json, re
txt = open("script.md").read()
KEYS = ['question', 'signals', 'update', 'scale', 'sheet', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("facts.json")); J = lambda k: " ".join(N[k])
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
k3, k2, kl = K['kimi_k3'], K['kimi_k2'], K['kimi_linear']
assert k3['kda_layers'] + k3['mla_layers'] == k3['layers'] == 93 and k3['kda_layers'] == 69 and k3['mla_layers'] == 24 and k3['params_total_T'] == 2.8 and k3['params_active_B'] == 104 and (k3['experts_active'], k3['experts_total']) == (16, 896) and k3['context_tokens_M'] == 1 and k3['scaling_efficiency_vs_k2'] == 2.5
assert k2['qk_clip_tau'] == 100 and k2['tokens_T'] == 15.5 and kl['kv_cache_reduction_pct'] == 75 and kl['decode_speedup'] == 6
has('signals', 'above a thousand', 'threshold of 100', '15.5 trillion tokens')
has('scale', '93 layers', '69 delta-attention layers and 24 full ones', '1 million tokens', '75 percent', '6 times', '896 experts', '16', '2.8 trillion', '104 billion', '2.5 times', 'three of every four')
has('sheet', '104 billion of 2.8 trillion')
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
