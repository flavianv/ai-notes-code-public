# Builds narration.json from script.md and data.js from results.json, and checks every spoken number.
import json, re
import numpy as np
txt = open("script.md").read()
KEYS = ['question', 'step', 'recipe', 'transfer', 'wrap', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("results.json")); J = lambda k: " ".join(N[k]); r = lambda v, n=2: round(v, n)
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
A = K['one_step']; assert [a['n'] for a in A] == [64, 128, 256, 512, 1024, 2048] and [r(-a['delta']) for a in A] == [.64, 1.28, 2.56, 5.12, 10.24, 20.48]
assert all(abs(a['delta'] - a['predicted']) < 1e-9 for a in A) and all(.9 < a['init_std'] < 1.2 for a in A) and r(A[-1]['delta'] / A[0]['delta'], 0) == 32
has('step', '0.64, 1.28, 2.56, 5.12, 10.24 and 20.48', '64, 128, 256, 512, 1,024 and 2,048', 'about 1', '32')
B = K['best_lr']['sp']; assert [B[str(n)] for n in K['widths']] == [.25, .25, .125, .0625, .0625, .03125]
L = K['losses']; lr = K['lrs']; i = lambda v: lr.index(v)
assert all(np.isnan(L['sp'][str(n)][i(.25)]) or L['sp'][str(n)][i(.25)] != L['sp'][str(n)][i(.25)] for n in (512, 1024, 2048)) and all(L['sp'][str(n)][i(.25)] == L['sp'][str(n)][i(.25)] for n in (64, 128, 256))
assert len(lr) == 13 and lr[0] == 2 ** -8 and lr[-1] == 16
assert all(.002 <= L['mup'][str(n)][i(.5)] <= .004 for n in K['widths']) and all(L['mup'][str(n)][i(2.0)] < 1e-4 for n in K['widths'])
has('transfer', '13 learning rates', '0.25 at widths 64 and 128', '0.125, 0.0625, 0.0625', '0.031', 'eight times', '512 and above', 'between 0.002 and 0.004', 'below 10 to the minus 4', '1,024 and 2,048')
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
