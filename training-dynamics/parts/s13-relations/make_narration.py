# Builds narration.json from script.md and data.js from results.json, and checks every spoken number.
import json, re
import numpy as np
txt = open("script.md").read()
KEYS = ['question', 'memory', 'relations', 'layers', 'wrap', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("results.json")); J = lambda k: " ".join(N[k]); r = lambda v, n=2: round(v, n)
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
ex = K['example']; assert ex['read1'] == [1.0, .6] and r(ex['dot']) == .6
M = {row['n']: row for row in K['memory']['rows']}; assert K['memory']['d'] == 64
assert all(M[n]['orthonormal'] < 1e-15 for n in (8, 16, 32, 64)) and [r(M[n]['theory']) for n in (16, 64, 128)] == [.48, .99, 1.41] and [r(M[n]['measured']) for n in (16, 64, 128)] == [.47, .99, 1.41]
has('memory', '0.6', '1, 0.6', '10 to the minus 15', '64', '0.48 for 16 pairs, 0.99 for 64 and 1.41 for 128', '0.47, 0.99 and 1.41')
A = K['additive']; assert r(A['resid'], 2) == .02 and [r(v, 1) for v in A['dir_norms']] == [3.0, 3.3, 3.4] and max(abs(A['dir_cos'][i][j]) for i in range(3) for j in range(3) if i != j) < .02
D = K['directions']; assert all(round(D['gender_cos'][i][j], 2) == 1.0 for i in range(4) for j in range(4)) and [r(v, 1) for v in D['gender_norms']] == [3.0, 3.0, 3.1, 3.0]
kq = K['king_queen']; assert kq['answer'] == 'queen' and r(kq['scores']['queen']) == 1.0 and r(kq['scores']['princess']) == .28 and K['analogies'] == {'total': 36, 'correct': 36}
has('relations', '2 percent', '3.0, 3.3 and 3.4', 'below 0.02', '1.00', '3.0, 3.0, 3.1 and 3.0', '0.28', '36 times', 'four numbers', '2013')
W = K['relation']['world']; C = K['relation']['conditions']; oh, em = C['one-hot ids'], C['learned embeddings']
assert W['entities'] == 32 and W['attributes'] == 5 and W['pairs'] == 160 and W['n_train'] == 96 and W['n_test'] == 64 and r(W['chance_exact'] * 100, 1) == 3.1
assert round(oh['train_acc'] * 100) == 100 and r(oh['test_acc'] * 100, 1) == 3.9 and r(em['test_acc'] * 100, 1) == 99.7
assert [round(oh['probes'][k] * 100) for k in ('input', 'hidden 1', 'hidden 2')] == [38, 89, 85] and all(round(em['probes'][k] * 100) == 100 for k in ('input', 'hidden 1', 'hidden 2'))
has('layers', '32 entities', 'five binary attributes', '160 pairs', '96 pairs', 'other 64', '64 units', '100 percent', '3.9 percent', '3.1 percent', '99.7 percent', '24 entities', '38 percent', '89 percent', '85 percent')
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
