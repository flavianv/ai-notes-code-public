# Builds narration.json from script.md and data.js from results.json, and checks every spoken number.
import json, re
txt = open("script.md").read()
KEYS = ['question', 'laws', 'budget', 'published', 'limits', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("results.json")); J = lambda k: " ".join(N[k]); r = lambda v, n=2: round(v, n)
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
f = K['fit']; Ls = K['L']
assert [int(v) for v in (K['N'][0], K['N'][-1])] == [1045, 55385] and [int(v) for v in (K['D'][0], K['D'][-1])] == [12800, 819200] and len(K['N']) * len(K['D']) == 24
assert r(Ls[0][0]) == 3.63 and r(Ls[-1][-1]) == 1.97
assert [r(f['E']), r(f['A'], 1), r(f['B'], 1), r(f['alpha']), r(f['beta']), r(f['rmse'])] == [1.26, 10.3, 19.8, .38, .27, .08]
Nc, Dc = K['N'][3], K['D'][2]; gN, gD = f['A'] * Nc ** -f['alpha'], f['B'] * Dc ** -f['beta']
assert Nc == 9677 and Dc == 204800 and r(gN) == .32 and r(gD) == .73 and r(f['E'] + gN + gD) == 2.31 and r(Ls[3][2]) == 2.33
has('laws', '1,045 to 55,385', '12,800 to 819,200', '24 runs', '3.63', '1.97', '1.26', '10.3', '19.8', '0.38', '0.27', '0.08', '9,677', '204,800', '0.32', '0.73', '2.31', '2.33')
assert r(f['alpha'] * f['A']) == 3.92 and r(f['beta'] * f['B']) == 5.36
o = K['optimal_toy'][1]; assert o['C'] == 1e11 and round(o['N'], -2) == 10900 and r(o['D'] / 1e6) == 1.53 and round(o['tokens_per_param'], -1) == 140
assert r(K['brute_N'] / 1e9) == 32.21 and r(K['optimal_hoffmann'][2]['N'] / 1e9) == 32.19
has('budget', '3.92', '5.36', '10,900', '1.53 million', '140 tokens per parameter', '4,000', '32.21 billion', '32.19 billion')
H = K['hoffmann']; assert [H['E'], H['A'], H['B'], H['alpha'], H['beta']] == [1.69, 406.4, 410.7, .34, .28]
EP = K['epoch']; assert [r(EP['E']), round(EP['A']), round(EP['B']), r(EP['alpha'], 3), r(EP['beta'], 3)] == [1.82, 482, 2085, .348, .366]
oh = K['optimal_hoffmann'][2]; oe = K['optimal_epoch'][2]; assert oh['C'] == 5.76e23 and round(oh['N'] / 1e9) == 32 and round(oh['D'] / 1e12) == 3 and round(oh['tokens_per_param']) == 93
assert round(oe['N'] / 1e9) == 72 and r(oe['D'] / 1e12) == 1.33 and r(oe['tokens_per_param'], 1) == 18.4
e0, e3 = K['optimal_epoch'][0], K['optimal_epoch'][3]; assert round(e0['tokens_per_param']) == 24 and round(e3['tokens_per_param']) == 17
has('published', '1.69', '406.4', '410.7', '0.34', '0.28', '1.82', '482', '2,085', '0.348', '0.366', '32 billion', '3 trillion', '93 tokens per parameter', '72 billion', '1.33 trillion', '18.4', '24 tokens per parameter', '17')
o3 = K['optimal_toy'][3]; assert round(o3['D'] / 1e6) == 23 or round(o3['D'] / 1e6) == 22; assert round(o3['D'] / K['D'][-1]) == 28 and o3['C'] == 1e13
has('limits', '140 tokens per parameter', '22 million', '28 times')
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
