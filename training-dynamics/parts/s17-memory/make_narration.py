# Builds narration.json from script.md and data.js from results.json, and checks every spoken number.
import json, re
txt = open("script.md").read()
KEYS = ['question', 'softmax', 'linear', 'delta', 'gates', 'code', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("results.json")); J = lambda k: " ".join(N[k]); r = lambda v, n=2: round(v, n)
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
C = {row['pairs']: row for row in K['capacity']['rows']}; Lc = K['linear']; St = K['state']
assert Lc['cost']['ratio'] == 64 and round(Lc['cost']['pairwise_madds'] / 1e9, 1) == 2.1 and round(Lc['cost']['recurrent_madds'] / 1e6) == 34 and Lc['state_entries'] == 72 and Lc['pairwise_vs_recurrent'] < 1e-15
assert St['kv_cache']['4096'] == 524288 and St['kv_cache']['128'] == 16384 and St['fixed'] == 4096 and St['kv_cache']['128'] // St['fixed'] == 4
assert max(row['softmax'] for row in K['capacity']['rows']) < 2e-8
has('softmax', '2.1 billion', '524,288', '2 times 10 to the minus 8', '16,384', '4,096')
has('linear', '10 to the minus 15', '72 numbers', '34 million', '2.1 billion', '64 times fewer')
assert K['collision']['additive_read'] == [1, 1] and K['collision']['delta_read_before'] == [1, 0] and K['collision']['delta_error'] == [-1, 1] and K['collision']['delta_read_after'] == [0, 1]
assert [r(C[n]['additive']) for n in (16, 64, 128)] == [.47, .98, 1.41]
has('linear', '1, 1', '0.47', '0.98', '1.41')
assert [r(C[n]['delta']) for n in (16, 64, 128)] == [.33, .72, .99] and r(K['delta_norm_max'], 4) == 1.0 and K['delta_checks']['chunk_vs_recurrent'] < 2e-15
has('delta', '1, 0', 'minus 1, 1', '0, 1', '1.0000', '2 times 10 to the minus 15', '0.33', '0.72', '0.99', '0.47, 0.98 and 1.41')
assert r(C[96]['gated_delta']) == .87 and r(C[96]['delta']) == .89 and r(C[128]['gated_delta']) == .93
has('gates', '0.98', '0.87', '0.89', '0.93', '0.99', 'three to one')
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
