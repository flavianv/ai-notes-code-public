# Builds narration.json from script.md and data.js from results.json, and checks every spoken number.
import json, re
import numpy as np
txt = open("script.md").read()
KEYS = ['question', 'idea', 'experiment', 'layers', 'ablate', 'wrap', 'refs']
blocks = [b for b in re.split(r"\n## ", txt)[1:] if b[:1].isdigit()]
assert len(blocks) == len(KEYS), len(blocks)
def sentences(p):
    ss = re.split(r"(?<=[.!?])\s+(?=[A-Z\"“])", p); out = []
    for s in ss:
        if out and len(out[-1].split()) + len(s.split()) <= 30 and len(s.split()) < 5: out[-1] += " " + s
        else: out.append(s)
    return out
N = {}
for key, block in zip(KEYS, blocks):
    vo = block.split("**Voice-over:**")[1].split("**Reader:**")[0].replace("---", "").strip()
    paras = [p.replace("\n", " ").replace("**", "").strip() for p in vo.split("\n\n")]
    N[key] = [s for p in paras if p for s in sentences(p)]
K = json.load(open("results.json")); J = lambda k: " ".join(N[k]); r = lambda v, n=2: round(v, n)
def has(k, *ss):
    for s in ss: assert s in J(k), (k, s)
S = K['seeds']; pc = lambda v: round(v * 100)
assert round(np.log(49), 1) == 3.9
a1 = [s['acc1'] for s in S]; a2 = [s['acc2'] for s in S]
assert [pc(v) for v in a1] == [6, 8, 10] and [round(v * 100, 1) for v in a2] == [99.7, 99.8, 99.8]
c1 = [np.array(s['curve1'])[-1, 2] for s in S]; assert min(c1) > 3.2
c2 = [np.array(s['curve2']) for s in S]
at = lambda c, st: float(c[list(c[:, 0]).index(st), 2])
assert sorted(round(at(c, 400), 1) for c in c2) == [3.3, 3.5, 3.5] and sorted(round(at(c, 600), 1) for c in c2) == [0.5, 0.6, 0.6] and sorted(round(c[-1, 2], 2) for c in c2) == [0.03, 0.03, 0.05] and round(c2[0][0, 2], 1) == 4.1
has('layers', '6 to 10 percent', '3.2', '99.7 to 99.8 percent', '400 steps', '4.1', 'between 3.3 and 3.5', 'step 600', 'between 0.5 and 0.6', 'between 0.03 and 0.05')
mp = [max(s['prev_l0'].values()) for s in S]; assert [pc(v) for v in mp] == [96, 94, 90]
ind = [v for s in S for v in s['ind_l1'].values()]; assert pc(min(ind)) == 87 and pc(max(ind)) == 92
has('layers', '96 percent', '94 and 90 percent', '87 to 92 percent')
ab = [s['ablate']['acc_ind_off'] for s in S]; assert all(round(v * 100) == 98 for v in ab) or all(97.5 <= v * 100 < 99.5 for v in ab)
g = [s['group'] for s in S]
assert [pc(x['all_prev_off']) for x in g] == [7, 8, 5] and [round(x['all_ind_off'] * 100) for x in g] == [2, 2, 2] and [pc(x['one_ind_kept']) for x in g] == [56, 63, 66] and [pc(x['non_prev_L0_off']) for x in g] == [81, 80, 83]
has('ablate', '98 percent', '99.8 to between 5 and 8 percent', 'about 2 percent', 'between 56 and 66 percent', 'around 80 percent')
l50 = [s['acc2_len50'] for s in S]; assert [pc(v) for v in l50] == [28, 19, 14]
has('wrap', 'between 14 and 28 percent', '32 tokens', '50')
has('experiment', '3.9', '4.0', '49', '20 tokens', '19 positions', '8 to 32 tokens', '64')
P = np.array(K['example']['pats']['0.0']); Q = np.array(K['example']['pats']['1.0']); assert all(np.argmax(P[i]) == i - 1 for i in range(1, 21)) and all(np.argmax(Q[i]) == i - 9 for i in range(12, 21))
json.dump(N, open("narration.json", "w"), indent=1)
open("data.js", "w").write("// generated by make_narration.py\nwindow.RES = {};\nwindow.RES0 = {};\nwindow.RES3 = {};\nwindow.LAB = " + json.dumps(K) + ";\n")
for k, v in N.items(): print(f"{k:10s} {len(v):2d} sentences {sum(len(s.split()) for s in v):4d} words")
tot = sum(len(s.split()) for v in N.values() for s in v); print("total", tot, "words, about", round(tot / 2.75 / 60, 1), "min")
